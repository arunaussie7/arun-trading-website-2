export function getCountryStat(name: string): CountryStat {
  const key = name.toLowerCase().trim();

  if (key.includes('antarctic')) return { clients: 0 };
  if (key === 'greenland' || key === 'w. sahara') return { clients: 0 };

  const aliased = ALIASES[key] ?? key;
  if (CLIENTS[aliased] !== undefined) return { clients: CLIENTS[aliased] };
  if (CLIENTS[key] !== undefined) return { clients: CLIENTS[key] };

  // Unlisted small territories — conservative demo default (not random)
  return { clients: 2 };
}

export function formatClients(n: number) {
  return n.toLocaleString('en-IN');
}
